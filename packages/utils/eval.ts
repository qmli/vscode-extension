/**
 * @warning 警告：这个函数使用了 `new Function()` 动态执行字符串中的代码。
 * 这**非常危险**，并且**绝对不应**使用不可信的输入。
 * 它可能导致严重的安全漏洞，比如代码注入、跨站脚本攻击（XSS）等，
 * 攻击者可以执行任意代码，控制你的应用程序。
 *
 * 这实际上等同于使用 `eval()`，两者都被认为是非常糟糕的实践。
 *
 * 仅当你**完全确信**输入是安全的，并且不来自用户输入时，才可以使用此函数。
 * 即使如此，也强烈建议避免在生产环境中使用。
 *
 * 推荐使用其他更安全的方法，例如 JSON 解析、严格的输入验证，
 * 或者使用沙箱环境来隔离代码执行。
 */
export function evil(str: string): any {
  return new Function(`return ${str}`)();
}
